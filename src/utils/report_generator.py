import os

def generate_markdown_report(title: str, spec: dict, sources: list, metrics: dict) -> str:
    filename = f"research_report_{title.replace(' ', '_')[:30]}.md"
    filepath = os.path.join(os.getcwd(), filename)
    
    content = f"""# Research Report: {title}

## 1. Research Specification
* **Objective**: {spec.get('objective', 'N/A')}
* **Detected Tools**: {', '.join(spec.get('tools', []))}

## 2. Retrieved Evidence & Literature
"""
    for s in sources:
        content += f"\n- **{s.get('title')}** ({s.get('authors_or_org')})\n  - *Summary*: {s.get('summary')}\n  - *URL*: {s.get('url')}\n"

    content += f"""
## 3. Simulation Metrics & Physics Parameters
* **Optical Power**: {metrics.get('power_watts')} W
* **Calculated Intensity**: {metrics.get('intensity_w_m2')} W/m²
* **Fresnel Number**: {metrics.get('fresnel_number')}

---
*Generated by AI Research Lab (Keyless Academic Workspace)*
"""
    with open(filepath, "w") as f:
        f.write(content)

    return filepath
